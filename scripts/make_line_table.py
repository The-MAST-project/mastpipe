"""Build the catalogue line table of one configuration from the UVES Th-Ar atlas.

Needs the atlas of Murphy et al. 2007, MNRAS 378, 221 (line list ``thar_MM201006.dat``)
and Murphy et al. 2010, ApJ 723, 89 (spectrum ``thar_spec_MM201006.fits``), which is not
part of the repository: the folder holding both files is read from the environment variable
``MASTPIPE_ATLAS_DIR``. The atlas functions come from :mod:`mastpipe.steps.atlas`; the
committed table is this script's own output and a rerun must reproduce it unchanged.

Criteria (from the HighSpec laboratory reduction notebook): the atlas spectrum in the band
plus a 0.5 nm pad has its pedestal removed (centred rolling 5th percentile over 201 samples)
and is convolved to the requested resolving power with a Gaussian of FWHM equal to the mean
wavelength over R. A catalogue line is usable when the centroid of the convolved feature
within +/-0.8 FWHM of the catalogue wavelength lies within 0.02 FWHM of it and its peak
above the baseline (rolling 10th percentile over 2001 samples) exceeds 20 times the noise
(1.4826 times the median absolute sample-to-sample difference).

Usage::

    MASTPIPE_ATLAS_DIR=<atlas folder> python scripts/make_line_table.py \\
        --instrument highspec --configuration mgb518 --resolving-power 23081

Writes ``src/mastpipe/instruments/<instrument>/lines/<configuration>.csv`` (the path the
configuration block declares as ``line_table``).
"""

from __future__ import annotations

import argparse
import csv
import os
import sys
from pathlib import Path

import pandas as pd

from mastpipe.instruments.registry import instrument_dir, load_instrument
from mastpipe.steps.atlas import (
    convolve_to_resolving_power,
    flag_usable_lines,
    load_murphy_atlas,
    remove_pedestal,
)

PAD_NM = 0.5
PEDESTAL_WINDOW = 201
PEDESTAL_PERCENTILE = 5
MAX_SHIFT_FWHM = 0.02
MIN_SNR = 20.0


def header_lines(
    instrument: str,
    configuration: str,
    band: tuple[float, float],
    resolving_power: float,
    n_usable: int,
    n: int,
) -> list[str]:
    """The comment block written above the CSV header."""
    return [
        f"{configuration}: Th-Ar catalogue lines in {band[0]:.1f}-{band[1]:.1f} nm (air)",
        "with a usable flag at the instrument resolution.",
        "Source: UVES Th-Ar atlas of Murphy et al. 2007, MNRAS 378, 221 (line list) and",
        "Murphy et al. 2010, ApJ 723, 89 (spectrum); wavelengths in air nm, logI as listed.",
        f"usable: atlas spectrum with its pedestal removed (rolling {PEDESTAL_PERCENTILE}th",
        f"percentile over {PEDESTAL_WINDOW} samples), convolved to R = {resolving_power:g}",
        "(Gaussian, FWHM = mean wavelength / R); true when the centroid of the convolved",
        f"feature within +/-0.8 FWHM of the catalogue wavelength lies within {MAX_SHIFT_FWHM:g}",
        "FWHM of it and its peak above the baseline (rolling 10th percentile over 2001",
        f"samples) exceeds {MIN_SNR:g} x the noise (1.4826 x median |diff|).",
        f"{n_usable} of {n} lines usable. Generated by scripts/make_line_table.py",
        f"--instrument {instrument} --configuration {configuration}",
        f"--resolving-power {resolving_power:g}",
    ]


def write_line_table(table: pd.DataFrame, path: Path, comments: list[str]) -> None:
    """Write ``wavelength_nm, species, logI, usable`` sorted by wavelength under ``comments``."""
    ordered = table.sort_values("wavelength", kind="stable")
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as handle:
        for line in comments:
            handle.write(f"# {line}\n")
        writer = csv.writer(handle)
        writer.writerow(["wavelength_nm", "species", "logI", "usable"])
        for row in ordered.itertuples(index=False):
            writer.writerow(
                [f"{row.wavelength:.7f}", row.species, f"{row.logI:.3f}", bool(row.usable)]
            )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--instrument", required=True)
    parser.add_argument("--configuration", required=True)
    parser.add_argument(
        "--resolving-power",
        type=float,
        default=None,
        help="resolving power of the convolution (default: the configuration block's value)",
    )
    args = parser.parse_args(argv)

    atlas_dir = os.environ.get("MASTPIPE_ATLAS_DIR")
    if not atlas_dir:
        print("MASTPIPE_ATLAS_DIR is not set; it must point at the Murphy atlas folder")
        return 2
    instrument = load_instrument(args.instrument)
    block = instrument.configurations[args.configuration]
    resolving_power = args.resolving_power or block.resolving_power
    relative = block.line_table or f"lines/{args.configuration}.csv"
    output = instrument_dir(args.instrument) / Path(relative)

    spectrum, catalogue = load_murphy_atlas(Path(atlas_dir), block.band_nm, pad=PAD_NM)
    wave = spectrum["wavelength"].to_numpy()
    flux = remove_pedestal(
        spectrum["flux"].to_numpy(), window=PEDESTAL_WINDOW, q=PEDESTAL_PERCENTILE
    )
    flux_conv, fwhm_nm = convolve_to_resolving_power(wave, flux, resolving_power)
    flagged = flag_usable_lines(
        wave, flux_conv, catalogue, fwhm_nm, max_shift=MAX_SHIFT_FWHM, min_snr=MIN_SNR
    )
    n_usable = int(flagged["usable"].sum())
    comments = header_lines(
        args.instrument, args.configuration, block.band_nm, resolving_power, n_usable, len(flagged)
    )
    write_line_table(flagged, output, comments)
    print(f"{len(flagged)} lines, {n_usable} usable -> {output.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
